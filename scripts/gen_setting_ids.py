"""Regenerate custom_components/spool_bridge/setting_ids.py from Bambu Studio's profiles.

usage: uv run python scripts/gen_setting_ids.py BAMBUSTUDIO/resources/profiles/BBL/filament
"""
from collections import Counter
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from custom_components.spool_bridge.model import _PROFILE_ID_RE, _setting_rule  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "custom_components" / "spool_bridge" / "setting_ids.py"


def main(root: str) -> None:
    profiles = {}
    for path in sorted(pathlib.Path(root).rglob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if "name" in data:
            profiles[data["name"]] = data

    def filament_id(name: str) -> str | None:
        seen = set()
        while name and name not in seen and name in profiles:
            seen.add(name)
            if profiles[name].get("filament_id"):
                return profiles[name]["filament_id"]
            name = profiles[name].get("inherits") or ""
        return None

    truth: dict[str, str] = {}
    for name, data in profiles.items():
        setting, fid = data.get("setting_id"), filament_id(name)
        if setting and fid:
            truth[setting.upper()] = fid.upper()
    filament_ids = {fid.upper() for name in profiles if (fid := filament_id(name))}

    by_base: dict[str, Counter[str]] = {}
    for setting, fid in truth.items():
        by_base.setdefault(setting.split("_")[0], Counter())[fid] += 1
    families: dict[str, str] = {}
    for base, counts in by_base.items():
        usual = counts.most_common(1)[0][0]
        if usual != _setting_rule(base):
            families[base] = usual
    exact: dict[str, str] = {}
    for setting, fid in truth.items():
        base = setting.split("_")[0]
        if families.get(base, _setting_rule(base)) != fid:
            exact[setting] = fid
    for fid in filament_ids:
        if families.get(fid, _setting_rule(fid)) != fid:
            exact[fid] = fid

    def block(name: str, table: dict[str, str]) -> list[str]:
        return [f"{name} = {{", *(f'    "{k}": "{table[k]}",' for k in sorted(table)), "}", ""]

    lines = [
        '"""Setting ids whose filament id does not follow the naming rule.',
        "",
        "Generated by scripts/gen_setting_ids.py from Bambu Studio's BBL filament profiles",
        f"({len(truth)} setting ids, {len(filament_ids)} filament ids). Do not edit by hand.",
        "SETTING_ID_FAMILIES: the usual filament id for a setting id without its _NN suffix.",
        "SETTING_ID_EXACT: single setting (or filament) ids that differ from that.",
        '"""',
        "",
        *block("SETTING_ID_FAMILIES", families),
        "",
        *block("SETTING_ID_EXACT", exact),
    ]
    def resolve(value: str) -> str | None:
        base = value.split("_")[0]
        if not _PROFILE_ID_RE.match(base):
            return None
        return exact.get(value) or families.get(base) or _setting_rule(base)

    expected = {**truth, **{fid: fid for fid in filament_ids}}
    unresolved = sorted(v for v, fid in expected.items() if resolve(v) != fid)
    if unresolved:
        sys.exit(f"not written, these ids would resolve wrongly: {unresolved}")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(truth)} setting ids, {len(filament_ids)} filament ids, "
          f"{len(families)} families, {len(exact)} exact -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
